import type { Product } from "@/data/products";

/**
 * Подборка товаров (например "Для завтрака", "Скидки недели"). Раньше это
 * был статичный файл со стикер-картинками и ссылкой на категорию — теперь
 * подборки реальные, хранятся в БД (Collection/CollectionItem) и содержат
 * конкретные товары, которые выбрал администратор.
 */
export interface Collection {
  slug: string;
  title: string;
  /** Обложка подборки. Если не задана — на клиенте используется фолбэк (фото первого товара). */
  image?: string;
  order: number;
  active?: boolean;
  /** Товары внутри подборки, в порядке, заданном администратором. */
  products: Product[];
}
